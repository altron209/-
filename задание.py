# ============================================================
#  Обратная программа (вариант 4)
#  Задача: найти наибольший элемент последовательности целых
#  чисел, введённых с клавиатуры в одну строку.
#  Алгоритм реализован по блок-схеме (см. flowchart.svg / png):
#  ввод -> инициализация -> цикл по элементам -> вывод.
#  Отличие от исходного образца: перебор организован циклом
#  while с индексом i вместо цикла for.
# ============================================================

# --- Блок 1: ВВОД ДАННЫХ ------------------------------------
# Читаем одну строку со стандартного ввода, разбиваем её
# по пробельным символам и каждый элемент преобразуем в int.
nums = list(map(int, input().split()))

# --- Блок 2: ИНИЦИАЛИЗАЦИЯ -----------------------------------
mx = nums[0]   # текущий максимум: полагаем им первый элемент
i = 0          # индекс текущего рассматриваемого элемента

# --- Блок 3: ЦИКЛ ПО ВСЕМ ЭЛЕМЕНТАМ СПИСКА -------------------
while i < len(nums):      # условие цикла: индекс в границах списка
    x = nums[i]           # текущий элемент последовательности
    if x > mx:            # условие: текущий элемент больше максимума?
        mx = x            # да -> запоминаем новый максимум
    i = i + 1             # переход к следующему элементу

# --- Блок 4: ВЫВОД РЕЗУЛЬТАТА --------------------------------
print(mx)                 # наибольший элемент последовательности